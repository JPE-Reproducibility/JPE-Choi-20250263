%%% TABLE2: Decomposing CR3 %%%%%%%%%%
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

matlab_dir = fileparts(mfilename('fullpath'));
if isempty(matlab_dir)
    matlab_dir = pwd;
end
project_root = fileparts(matlab_dir);
if isfolder(fullfile(matlab_dir,'INPUT')) && isfolder(fullfile(matlab_dir,'MATLAB'))
    project_root = matlab_dir;
    matlab_dir = fullfile(project_root,'MATLAB');
end
if ~isfolder(fullfile(project_root,'INPUT'))
    error('making_table2:InvalidProjectRoot', ...
        'Expected INPUT/ at the Replication_JPE root; resolved root: %s',project_root);
end
addpath(matlab_dir);
table = string(fullfile(project_root,'TABLE')) + filesep;
if ~isfolder(table)
    mkdir(table);
end

[continuing_margin_10,entry_exit_margin_10,sector_margin_10,productivity_margin_10,export_margin_10] = CR3_decompose(1,Par,est_result,result);
total_margin_10 = continuing_margin_10 + entry_exit_margin_10 + sector_margin_10;
within_margin_10 = productivity_margin_10 + export_margin_10 + entry_exit_margin_10;


Fid = fopen(table + "TABLE2.tex",'w');

fprintf(Fid,'%s\n','\begin{tabular}{lcccccc}');
fprintf(Fid,'%s\n','\toprule');
fprintf(Fid,'%s\n','Period & 1972--1982 & 1982--1992 & 1992--2002 & 2002--2011 & & 1972--2011 \\');
fprintf(Fid,'%s\n','\midrule');

% --- helper handles (optional but keeps formatting consistent)
blankrow = @() fprintf(Fid,'%s\n','& & & & & & \\');

% --- 1) Delta Agg. Top-3 CR
fprintf(Fid,'%s','$\triangle$ Agg. Top-3 CR (pp) ');
fprintf(Fid,'& %2.2f & %2.2f & %2.2f & %2.2f && %2.2f \\\\ \n', ...
    (CR3_result(11)-CR3_result(1))*100, ...
    (CR3_result(21)-CR3_result(11))*100, ...
    (CR3_result(31)-CR3_result(21))*100, ...
    (CR3_result(40)-CR3_result(31))*100, ...
    (CR3_result(40)-CR3_result(1))*100);

blankrow();

% --- 2) Within-sector component
fprintf(Fid,'%s','Within-sector component ');
fprintf(Fid,'& %2.2f & %2.2f & %2.2f & %2.2f && %2.2f \\\\ \n', ...
    sum(within_margin_10(1:10))/sum(total_margin_10(1:10))*(CR3_result(11)-CR3_result(1))*100, ...
    sum(within_margin_10(11:20))/sum(total_margin_10(11:20))*(CR3_result(21)-CR3_result(11))*100, ...
    sum(within_margin_10(21:30))/sum(total_margin_10(21:30))*(CR3_result(31)-CR3_result(21))*100, ...
    sum(within_margin_10(31:39))/sum(total_margin_10(31:39))*(CR3_result(40)-CR3_result(31))*100, ...
    sum(within_margin_10)/sum(total_margin_10)*(CR3_result(40)-CR3_result(1))*100);

% --- 2a) Productivity
fprintf(Fid,'%s','\hspace*{3mm} Cont. Top 3 -- Productivity ');
fprintf(Fid,'& %2.2f & %2.2f & %2.2f & %2.2f && %2.2f \\\\ \n', ...
    sum(productivity_margin_10(1:10))/sum(total_margin_10(1:10))*(CR3_result(11)-CR3_result(1))*100, ...
    sum(productivity_margin_10(11:20))/sum(total_margin_10(11:20))*(CR3_result(21)-CR3_result(11))*100, ...
    sum(productivity_margin_10(21:30))/sum(total_margin_10(21:30))*(CR3_result(31)-CR3_result(21))*100, ...
    sum(productivity_margin_10(31:39))/sum(total_margin_10(31:39))*(CR3_result(40)-CR3_result(31))*100, ...
    sum(productivity_margin_10)/sum(total_margin_10)*(CR3_result(40)-CR3_result(1))*100);

% --- 2b) Exports
fprintf(Fid,'%s','\hspace*{3mm} Cont. Top 3 -- Exports ');
fprintf(Fid,'& %2.2f & %2.2f & %2.2f & %2.2f && %2.2f \\\\ \n', ...
    sum(export_margin_10(1:10))/sum(total_margin_10(1:10))*(CR3_result(11)-CR3_result(1))*100, ...
    sum(export_margin_10(11:20))/sum(total_margin_10(11:20))*(CR3_result(21)-CR3_result(11))*100, ...
    sum(export_margin_10(21:30))/sum(total_margin_10(21:30))*(CR3_result(31)-CR3_result(21))*100, ...
    sum(export_margin_10(31:39))/sum(total_margin_10(31:39))*(CR3_result(40)-CR3_result(31))*100, ...
    sum(export_margin_10)/sum(total_margin_10)*(CR3_result(40)-CR3_result(1))*100);

% --- 2c) Entry & exit
fprintf(Fid,'%s','\hspace*{3mm} Entry \& exit ');
fprintf(Fid,'& %2.2f & %2.2f & %2.2f & %2.2f && %2.2f \\\\ \n', ...
    sum(entry_exit_margin_10(1:10))/sum(total_margin_10(1:10))*(CR3_result(11)-CR3_result(1))*100, ...
    sum(entry_exit_margin_10(11:20))/sum(total_margin_10(11:20))*(CR3_result(21)-CR3_result(11))*100, ...
    sum(entry_exit_margin_10(21:30))/sum(total_margin_10(21:30))*(CR3_result(31)-CR3_result(21))*100, ...
    sum(entry_exit_margin_10(31:39))/sum(total_margin_10(31:39))*(CR3_result(40)-CR3_result(31))*100, ...
    sum(entry_exit_margin_10)/sum(total_margin_10)*(CR3_result(40)-CR3_result(1))*100);

blankrow();

% --- 3) Across-sector component
fprintf(Fid,'%s','Across-sector component ');
fprintf(Fid,'& %2.2f & %2.2f & %2.2f & %2.2f && %2.2f \\\\ \n', ...
    sum(sector_margin_10(1:10))/sum(total_margin_10(1:10))*(CR3_result(11)-CR3_result(1))*100, ...
    sum(sector_margin_10(11:20))/sum(total_margin_10(11:20))*(CR3_result(21)-CR3_result(11))*100, ...
    sum(sector_margin_10(21:30))/sum(total_margin_10(21:30))*(CR3_result(31)-CR3_result(21))*100, ...
    sum(sector_margin_10(31:39))/sum(total_margin_10(31:39))*(CR3_result(40)-CR3_result(31))*100, ...
    sum(sector_margin_10)/sum(total_margin_10)*(CR3_result(40)-CR3_result(1))*100);

fprintf(Fid,'%s\n','\bottomrule');
fprintf(Fid,'%s\n','\end{tabular}');
fclose(Fid);
